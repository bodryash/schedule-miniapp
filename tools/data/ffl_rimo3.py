def main():
    sched = json.loads((DIR / "schedule.json").read_text(encoding="utf-8"))
    groups = json.loads((DIR / "groups.json").read_text(encoding="utf-8"))
    ids = {G1, G2}
    lessons = []
    for row in L:
        g, day, slot, subj, teacher, room, *rest = row
        rest = list(rest) + [None, "all", None, ""][len(rest):]
        sub, week, elect, note = rest[:4]
        lessons.append({"group": g, "day": day, "slot": slot, "subgroup": sub, "elective": elect,
                        "week": week or "all", "note": note or "", "link": "", "start": "", "end": "",
                        "type": "", "subject": subj, "room": room, "teacher": teacher})
    sched["lessons"] = [l for l in sched["lessons"] if l["group"] not in ids] + lessons
    new = [{"id": g, "title": g, "course": 3, "level": "бакалавриат"} for g in (G1, G2)]
    groups = [g for g in groups if g["id"] not in ids] + new
    sched["groups"] = [g for g in sched.get("groups", groups) if g["id"] not in ids] + new
    (DIR / "schedule.json").write_text(json.dumps(sched, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    (DIR / "groups.json").write_text(json.dumps(groups, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"РИМО: {len(lessons)} строк")


if __name__ == "__main__":
    main()
