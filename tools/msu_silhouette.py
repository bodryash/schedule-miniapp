"""Силуэт ГЗ МГУ, обведённый по фото Sergei Gussev (CC BY 2.0, Wikimedia Commons).

Точки контура сняты по сетке на снимке (координаты фото, ось здания x = 972,
земля y = 1105). Рисуем левую половину и отражаем.
"""
import sys

AXIS, GROUND, LEFT = 972, 1105, 380
opacity = sys.argv[1] if len(sys.argv) > 1 else "1"
color = sys.argv[2] if len(sys.argv) > 2 else "%23e2b862"

# Верхний контур левой половины: (x, y) по порядку слева направо.
top = [
    (LEFT, 1082), (462, 1082),            # дальнее низкое крыло
    (462, 946), (464, 946), (465.5, 909), (467, 946),   # угловая башня, шпилёк
    (481, 946), (481, 846), (502, 846), (502, 806), (509, 806), (509, 781),
    (534, 781), (534, 806), (543, 806), (543, 846), (559, 846),
    (562, 846), (562, 834), (572, 834), (574, 815), (576, 834), (587, 834),   # башенка
    (587, 946), (592, 946), (593.5, 868), (595, 946), (624, 946),
    (624, 959), (765, 959),               # крыло
    (765, 927), (780, 927), (782, 904), (784, 927), (799, 927),   # башенка на крыле
    (799, 959), (832, 959),
    (832, 777), (833, 777), (834.5, 745), (836, 777), (899, 777),  # центральный корпус
    (899, 598), (903, 598), (905, 567), (907, 598), (920, 598),    # ствол башни
    (920, 558), (928, 558), (928, 487), (931, 487), (932.5, 473), (934, 487),
    (942, 487), (942, 440), (950, 440), (950, 400), (958, 400),
    (958, 362), (965, 362),               # «фонарик»
    (969.5, 262), (AXIS, 258),            # шпиль
]
# Отражаем: правая половина — те же точки справа налево.
right = [(2 * AXIS - x, y) for x, y in reversed(top[:-1])]
points = [(LEFT, GROUND)] + top + right + [(2 * AXIS - LEFT, GROUND)]
d = "M" + "L".join(f"{x - LEFT:g} {y - 200:g}" for x, y in points) + "Z"
# Звезда в кольце над шпилем.
cx, cy, r = AXIS - LEFT, 240 - 200, 17
ring = f"M{cx} {cy - r}a{r} {r} 0 1 0 0.01 0Z"
import math
star = []
for k in range(10):
    ang = -math.pi / 2 + k * math.pi / 5
    rr = 11 if k % 2 == 0 else 4.5
    star.append(f"{cx + rr * math.cos(ang):.1f} {cy + rr * math.sin(ang):.1f}")
star_d = "M" + "L".join(star) + "Z"
w, h = 2 * (AXIS - LEFT), GROUND - 200
svg = (
    f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {w} {h}'>"
    f"<path fill='{color}' fill-opacity='{opacity}' d='{d}{star_d}'/>"
    f"<path fill='none' stroke='{color}' stroke-opacity='{opacity}' stroke-width='4' d='{ring}'/>"
    "</svg>"
)
sys.stdout.write(svg)
